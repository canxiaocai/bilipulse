_ZONE_LOCK = threading.Lock()
_DYNAMIC_V2_PRIMARY: dict[int, str] = {}
_DYNAMIC_V2_SUB: dict[int, tuple[int, str]] = {}


def merge_channel_kv(channel_kv: list[dict[str, Any]]) -> int:
    """Merge live channelKv entries from Bilibili into the runtime V2 zone registry."""
    if not isinstance(channel_kv, list):
        return 0
    added = 0
    with _ZONE_LOCK:
        for ch in channel_kv:
            if not isinstance(ch, dict):
                continue
            raw_pid = ch.get("tid")
            pname = str(ch.get("name") or "").strip()
            try:
                pid = int(raw_pid)
            except (TypeError, ValueError):
                continue
            if pid <= 0 or not pname:
                continue
            if _DYNAMIC_V2_PRIMARY.get(pid) != pname and V2_PRIMARY_ZONES.get(pid) != pname:
                added += 1
            _DYNAMIC_V2_PRIMARY[pid] = pname

            subs = ch.get("sub")
            if not isinstance(subs, list):
                continue
            for sub in subs:
                if not isinstance(sub, dict):
                    continue
                raw_sid = sub.get("tid")
                sname = str(sub.get("name") or "").strip()
                try:
                    sid = int(raw_sid)
                except (TypeError, ValueError):
                    continue
                if sid <= 0 or not sname:
                    continue
                entry = (pid, sname)
                if _DYNAMIC_V2_SUB.get(sid) != entry and V2_SUB_ZONES.get(sid) != entry:
                    added += 1
                _DYNAMIC_V2_SUB[sid] = entry
    return added


def has_known_v2_tid(tid_v2: int) -> bool:
    """Return True if tid_v2 exists in either the static or dynamically merged V2 registry."""
    try:
        val = int(tid_v2 or 0)
    except (TypeError, ValueError):
        return False
    if val <= 0:
        return False
    with _ZONE_LOCK:
        return (
            val in _DYNAMIC_V2_SUB
            or val in V2_SUB_ZONES
            or val in _DYNAMIC_V2_PRIMARY
            or val in V2_PRIMARY_ZONES
        )


def resolve_video_zone(
    tid: int = 0,
    tid_v2: int = 0,
    *,
    tname: str = "",
    tname_v2: str = "",
) -> dict[str, str]:
    """Resolve primary and secondary partition names, preferring Bilibili V2 (tid_v2) with V1 fallback."""
    try:
        v2_id = max(0, int(tid_v2 or 0))
    except (TypeError, ValueError):
        v2_id = 0
    try:
        v1_id = max(0, int(tid or 0))
    except (TypeError, ValueError):
        v1_id = 0

    clean_tname_v2 = str(tname_v2 or "").strip()
    clean_tname = str(tname or "").strip()

    if v2_id > 0:
        with _ZONE_LOCK:
            sub_entry = _DYNAMIC_V2_SUB.get(v2_id) or V2_SUB_ZONES.get(v2_id)
            if sub_entry is not None:
                parent_id, sub_name = sub_entry
                primary_name = (
                    _DYNAMIC_V2_PRIMARY.get(parent_id)
                    or V2_PRIMARY_ZONES.get(parent_id)
                    or ""
                )
                return {
                    "zone_primary": primary_name,
                    "zone_sub": clean_tname_v2 or sub_name,
                    "zone_version": "v2",
                }
            primary_only = _DYNAMIC_V2_PRIMARY.get(v2_id) or V2_PRIMARY_ZONES.get(v2_id)
            if primary_only:
                return {
                    "zone_primary": primary_only,
                    "zone_sub": clean_tname_v2,
                    "zone_version": "v2",
                }
        if clean_tname_v2:
            return {
                "zone_primary": "",
                "zone_sub": clean_tname_v2,
                "zone_version": "v2",
            }

    if v1_id > 0:
        v1_entry = V1_ZONES.get(v1_id)
        if v1_entry is not None:
            primary_name, sub_name = v1_entry
            return {
                "zone_primary": primary_name,
                "zone_sub": clean_tname or sub_name,
                "zone_version": "v1",
            }
        if clean_tname:
            return {
                "zone_primary": "",
                "zone_sub": clean_tname,
                "zone_version": "v1",
            }

    return {"zone_primary": "", "zone_sub": "", "zone_version": ""}
